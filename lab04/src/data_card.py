"""Generate lab04/data_card.md from the numbers computed in the pipeline run."""
from pathlib import Path

import lib


def write_card(root, cfg, typed, rep, split, audit, leak, metrics, manifest):
    n = len(typed)
    pos = cfg["data"]["positive_label"]
    y = typed[lib.TARGET] == pos
    pct = lambda x: f"{100 * x:.1f}%"

    def rate(col):
        g = y.groupby(typed[col].astype(str)).agg(["mean", "size"])
        return g

    sex, race = rate("sex"), rate("race")
    qi = ["age", "sex", "race", "native-country", "education", "occupation", "marital-status"]
    key = typed[qi].astype(str).agg("|".join, axis=1)
    counts = key.map(key.value_counts())
    unique_share = (counts == 1).mean()
    k5_share = (counts < 5).mean()
    us = (typed["native-country"] == "United-States").mean()
    miss = rep["missing_marker_counts"]
    p = manifest["processed"]
    d = audit["duplicate_conflicts_14_features"]
    d13 = audit["duplicate_conflicts_13_features_without_fnlwgt"]
    m = metrics.set_index("derived_features")

    def chk(name):
        return next(c["n"] for c in rep["checks"] if c["check"] == name)

    occ_missing = typed["occupation"] == cfg["data"]["missing_token"]
    miss_rate, other_rate = y[occ_missing].mean(), y[~occ_missing].mean()

    sex_rows = "\n".join(f"  - {k}: {pct(v['mean'])} earn >50K (n = {int(v['size'])})" for k, v in sex.iterrows())
    race_rows = "\n".join(f"  - {k}: {pct(v['mean'])} earn >50K (n = {int(v['size'])})" for k, v in race.iterrows())

    card = f"""# Data card: UCI Adult ("Census Income"), as used in Lab 4

*Generated by `lab04/src/run_pipeline.py` (rerunning the pipeline rewrites this file; use `--skip-card` to keep manual edits).*

## 1. Source and provenance

- **Dataset:** Adult / Census Income, UCI Machine Learning Repository, created by Ron Kohavi and donated 30 April 1996. According to the UCI page, Barry Becker extracted the records from the 1994 US Census database.
- **Citation:** Kohavi, R. (1996). *Census Income* [Dataset]. UCI Machine Learning Repository. https://doi.org/10.24432/C5GP7S
- **Loaded in this lab from:** a CSV copy of the 48,842-row UCI data (`{cfg['data']['raw_url']}`) because OpenML (`fetch_openml('adult', version=2)`) was not reachable from the environment where the pipeline was built. `--source openml` reads the OpenML copy instead. Raw file SHA256: `{manifest['ingestion']['raw_sha256']}` (verified on every run).
- **Raw data are never modified.** All cleaning happens on copies, after the train/test split.

## 2. License

Creative Commons Attribution 4.0 International (CC BY 4.0), as stated on the UCI page. Attribution to the creator and UCI is required (see citation).

## 3. Size and structure

- **{n:,} rows, {rep['columns']} columns:** 14 input features (6 integer, 8 categorical) and the label `income` (`<=50K` / `>50K`).
- **Label balance:** {int(y.sum()):,} rows `>50K` ({pct(y.mean())}), {int((~y).sum()):,} rows `<=50K` ({pct(1 - y.mean())}). Always predicting `<=50K` gives {pct(1 - y.mean())} accuracy.
- **Missing values** (marked `?`): workclass {miss.get('workclass', 0):,} ({pct(miss.get('workclass', 0) / n)}), occupation {miss.get('occupation', 0):,} ({pct(miss.get('occupation', 0) / n)}), native-country {miss.get('native-country', 0):,} ({pct(miss.get('native-country', 0) / n)}). The UCI page lists missing values only for workclass and occupation; native-country also has them.
- **Split used:** 70/30 stratified on the label (seed {cfg['seed']}) before any cleaning: {split['train_rows_before_dedupe']:,} train rows ({split['train_rows']:,} after dropping {split['train_duplicates_dropped']} exact duplicates from train only) and {split['test_rows']:,} test rows, untouched.
- **Processed dataset:** cleaned and feature-engineered tables (`data/processed/processed_train.csv`, `processed_test.csv`, not committed). SHA256 of train: `{p['sha256_train']}`; of test: `{p['sha256_test']}`; combined: `{p['sha256_combined']}`.

## 4. Preparation steps

1. Validation (`results/validation_report.md`): schema and types, value ranges, category lists from the data dictionary, `?` handling, duplicates and consistency checks; {rep['n_hard_violations']} hard-rule violations. No row is dropped by validation.
2. Imputation fitted on train only: mode for categorical columns (e.g. workclass `{leak['imputation_modes_from_train']['workclass']}`, occupation `{leak['imputation_modes_from_train']['occupation']}`), median for numeric columns (the numeric columns have no missing values, so this step changes nothing).
3. Numeric columns clipped to the train 1st/99th percentiles (e.g. capital-gain to [{leak['clip_lower_from_train']['capital-gain']:.0f}, {leak['clip_upper_from_train']['capital-gain']:.0f}], which also caps the 99999 values).
4. Derived features `capital_net = capital-gain - capital-loss` and `hours_per_age = hours-per-week / (age - 16)`; standard scaling and one-hot encoding fitted on train only before modelling.
5. The fitted transformer is saved as `results/preprocessor.joblib`.

## 5. Known biases and limitations

- **Old and US-specific:** data from 1994; the `>50K` threshold is in 1994 dollars. {pct(us)} of rows have native-country United-States.
- **Unequal group representation and outcomes.** Share of rows: {', '.join(f"{k} {pct(v['size'] / n)}" for k, v in sex.iterrows())} by sex; {', '.join(f"{k} {pct(v['size'] / n)}" for k, v in race.iterrows())} by race. Label rates differ strongly between groups:
{sex_rows}
{race_rows}
  These gaps reflect the historical income distribution in the data, not a property of the people; a model trained on the labels will reproduce them.
- **Sensitive attributes are features:** `sex`, `race`, `age` and `native-country` are inputs, and proxies for them exist (`relationship`, `marital-status`, `occupation`). Removing the sensitive columns would not remove the information.
- **Missingness is probably not random:** workclass and occupation are missing together in all but {chk('workclass and occupation missing together')} rows, and rows with a missing occupation earn `>50K` far less often ({pct(miss_rate)} vs {pct(other_rate)} for the rest). Imputing the mode (e.g. `Private`, `Prof-specialty`) therefore invents values that are likely wrong for many of these rows, and the information that a value was missing is lost (the pipeline adds no missing-indicator column, as the lab does not ask for one).
- **Top-coded values:** age {typed['age'].max()} ({int((typed['age'] == typed['age'].max()).sum())} rows), hours-per-week 99 ({int((typed['hours-per-week'] == 99).sum())} rows) and capital-gain 99999 ({int((typed['capital-gain'] == 99999).sum())} rows) sit at the maximum of their ranges and are probably "or more" codes that the data dictionary does not document.
- **Label noise:** {chk('exact duplicate rows (all 15 columns)')} exact duplicate rows exist. Among rows with identical values of all 14 features there are {d['conflicting_groups']} groups ({d['rows_in_conflicting_groups']} rows) with conflicting labels; if the census weight `fnlwgt` is ignored, {d13['conflicting_groups']:,} groups ({d13['rows_in_conflicting_groups']:,} rows, {d13['share_of_all_rows_pct']}% of the data) share identical demographics but different labels. This puts a ceiling on achievable accuracy.
- **Duplicates across the split:** {audit['train_test_conflicts']['test_rows_with_feature_twin_in_train']} test rows have an identical-feature twin in train (counted after dropping train duplicates); the test set is kept untouched as required, so test scores are very slightly optimistic. See `results/baseline_metrics.csv` for scores without these rows.
- **The sampling weight `fnlwgt` is used as an ordinary feature**, which is questionable: it describes how many people the row represents, not the person.

## 6. Privacy concerns

- There are no direct identifiers (no names, addresses or ID numbers).
- The remaining columns are quasi-identifiers. Using only seven of them (age, sex, race, native-country, education, occupation, marital-status), {pct(unique_share)} of rows are unique in the dataset and {pct(k5_share)} appear fewer than 5 times. I did not test re-identification against any external dataset, so this is an indicator only.
- The UCI page contains no statement about de-identification methods or about consent to this use of the data. Race, sex and country of origin are sensitive attributes in many legal frameworks (for example the GDPR's special categories for racial or ethnic origin).
- Do not attempt to link rows to real people, and do not publish enriched versions of the data.

## 7. Intended and unintended use

- **Intended:** teaching and benchmarking of tabular pipelines and fairness analysis.
- **Not suitable for:** decisions about real people (credit, hiring, housing, benefits). The labels and features encode 1994 income disparities, and this data cannot justify a model deployed on current populations.

## 8. Baseline reference (logistic regression, test set)

| Derived features | Accuracy | F1 (`>50K`) |
|---|---|---|
| none | {m.loc['none', 'test_accuracy']:.4f} | {m.loc['none', 'test_f1']:.4f} |
| capital_net | {m.loc['capital_net', 'test_accuracy']:.4f} | {m.loc['capital_net', 'test_f1']:.4f} |
| hours_per_age | {m.loc['hours_per_age', 'test_accuracy']:.4f} | {m.loc['hours_per_age', 'test_f1']:.4f} |
| both | {m.loc['both', 'test_accuracy']:.4f} | {m.loc['both', 'test_f1']:.4f} |

## 9. Reproduce

```
python lab04/src/run_pipeline.py
```

Configuration: `lab04/config.yaml`. Run record (versions, hashes, commit): `lab04/results/run_manifest.yaml`.
"""
    Path(root / "lab04" / "data_card.md").write_text(card)
